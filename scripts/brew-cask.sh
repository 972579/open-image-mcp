#!/usr/bin/env bash
# Print the Homebrew cask for one release, for the tap 972579/homebrew-tap.
#
#   scripts/brew-cask.sh VERSION BUILD_DIR [REPO]
#
# BUILD_DIR must hold genimage-VERSION-darwin-arm64.zip and
# genimage-VERSION-darwin-amd64.zip, the zips viva package wrote; their SHA-256
# go into the cask. REPO ("owner/name") is where the release is published and
# defaults to the one in internal/version/version.go. scripts/release.sh calls
# this and pushes the result to the tap; users then install with
#
#   brew install --cask 972579/tap/genimage-mcp
#
# The app is signed ad hoc and not notarized, so Homebrew's quarantine flag
# would make Gatekeeper ask on first open; the postflight step clears it for
# the installed app (Homebrew no longer offers --no-quarantine). The cask uses
# the Homebrew 5+ DSL (postflight_steps, depends_on macos: :ventura meaning
# "Ventura or newer"). auto_updates tells
# brew the app replaces itself (the in-app updater), so `brew upgrade` leaves it
# alone unless --greedy is given.
set -euo pipefail

if [[ $# -lt 2 ]]; then
  echo "usage: $0 VERSION BUILD_DIR [REPO]" >&2
  exit 2
fi
VERSION="$1"
BUILD="$2"
cd "$(dirname "$0")/.."
REPO="${3:-$(sed -n 's/^const Repo = "\(.*\)"/\1/p' internal/version/version.go)}"

# sha_of prints the SHA-256 of the macOS zip for one architecture, or fails
# with a message naming the missing file.
sha_of() {
  local file="$BUILD/genimage-${VERSION}-darwin-$1.zip"
  if [[ ! -f "$file" ]]; then
    echo "error: $file not found; run viva package for darwin/$1 first" >&2
    exit 1
  fi
  shasum -a 256 "$file" | cut -d' ' -f1
}
ARM_SHA="$(sha_of arm64)"
INTEL_SHA="$(sha_of amd64)"

cat <<EOF
# Generated by scripts/brew-cask.sh in ${REPO}; edits here are overwritten
# by the next release.
cask "genimage-mcp" do
  arch arm: "arm64", intel: "amd64"

  version "${VERSION}"
  sha256 arm:   "${ARM_SHA}",
         intel: "${INTEL_SHA}"

  url "https://github.com/${REPO}/releases/download/v#{version}/genimage-#{version}-darwin-#{arch}.zip"
  name "GenImage MCP"
  desc "Serve OpenAI-compatible image generation as MCP tools"
  homepage "https://github.com/${REPO}"

  livecheck do
    url :url
    strategy :github_latest
  end

  auto_updates true
  depends_on macos: :ventura

  app "GenImage MCP.app"

  # The app is signed ad hoc, not notarized: clear the quarantine flag so
  # Gatekeeper does not block the first launch.
  postflight_steps do
    run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{appdir}}/GenImage MCP.app"]
  end

  uninstall quit: "local.genimage.mcp"

  zap trash: "~/.gen-openai-image"

  caveats <<~CAVEATS
    GenImage MCP is signed ad hoc and not notarized by Apple. This cask
    removes the quarantine flag after installing so macOS opens it without
    the Gatekeeper prompt.

    The app updates itself from the About page; brew upgrade skips it unless
    you pass --greedy.
  CAVEATS
end
EOF
